"""Write build/readmissions_full_setup.sql: the whole database in one script.

For MySQL Workbench users, or any server where LOAD DATA LOCAL is switched
off. The raw rows are written as INSERT statements, so the script needs no
server settings and no command line.

    python scripts/make_one_file_setup.py

Then either
    Workbench:  File > Run SQL Script... > build/readmissions_full_setup.sql
    or          mysql -u root -p -e "source build/readmissions_full_setup.sql"

The script it writes runs, in order: 01_create_schema.sql, the raw rows,
04_build_clean_model.sql, and the views defined in 05 and 06. The audit
(03) and the analysis queries are left for you to run and read.
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw" / "diabetic_data.csv"
SQL = ROOT / "sql"
OUT = ROOT / "build" / "readmissions_full_setup.sql"
ROWS_PER_INSERT = 500


def literal(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def view_statements(path: Path) -> list[str]:
    """Every CREATE OR REPLACE VIEW statement in a script, up to its closing semicolon."""
    return re.findall(r"^CREATE OR REPLACE VIEW .*?;[ \t]*$", path.read_text(encoding="utf-8"), flags=re.S | re.M)


def main() -> None:
    OUT.parent.mkdir(exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="\n") as out, RAW.open(newline="", encoding="utf-8") as raw:
        out.write("-- Generated by scripts/make_one_file_setup.py. Do not edit; edit the scripts in sql/ instead.\n\n")
        out.write((SQL / "01_create_schema.sql").read_text(encoding="utf-8"))

        out.write("\n-- ---------------------------------------------------------------------\n")
        out.write("-- Raw rows from data/raw/diabetic_data.csv, loaded as text.\n")
        out.write("-- ---------------------------------------------------------------------\n")
        reader = csv.reader(raw)
        next(reader)  # header
        batch, total = [], 0
        for row in reader:
            batch.append("(" + ",".join(literal(cell) for cell in row) + ")")
            total += 1
            if len(batch) == ROWS_PER_INSERT:
                out.write("INSERT INTO stg_encounters VALUES\n" + ",\n".join(batch) + ";\n")
                batch = []
        if batch:
            out.write("INSERT INTO stg_encounters VALUES\n" + ",\n".join(batch) + ";\n")

        out.write("\n" + (SQL / "04_build_clean_model.sql").read_text(encoding="utf-8"))

        views = view_statements(SQL / "05_analysis.sql") + view_statements(SQL / "06_risk_tiers.sql")
        out.write("\n-- ---------------------------------------------------------------------\n")
        out.write("-- Result views from 05_analysis.sql and 06_risk_tiers.sql.\n")
        out.write("-- ---------------------------------------------------------------------\n")
        out.write("\n\n".join(views) + "\n\n")
        out.write("SELECT 'Setup complete' AS status, COUNT(*) AS index_stays FROM v_index_stays;\n")

    size_mb = OUT.stat().st_size / 1_000_000
    print(f"{OUT.relative_to(ROOT)}: {total:,} rows, {len(views)} views, {size_mb:.1f} MB")


if __name__ == "__main__":
    main()
